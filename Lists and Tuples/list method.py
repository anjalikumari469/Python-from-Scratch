list =[5,4,1] #append method
list.append(7)
print(list)

#sort method
list.sort() #ascending order
print(list)

list.sort(reverse=True) #descending order
print(list)

list.reverse() #reverse
print(list)

list.insert(1,8) #insert(index,element)
print(list)

list.remove(4) #remove
print(list)

list.pop(2) #pop
print(list)